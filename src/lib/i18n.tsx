type I18nContextValue = {
  lang: LangCode;
  dir: "ltr" | "rtl";
  setLang: (lang: LangCode) => void;
  t: (key: string, fallback?: string) => string;
};

const I18nContext = createContext<I18nContextValue>({
  lang: "en",
  dir: "ltr",
  setLang: () => {},
  t: (key, fallback) => EN[key] ?? fallback ?? key,
});

function readStoredLang(): LangCode {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved && LANGS.some((l) => l.code === saved)) return saved as LangCode;
  } catch {
    // Ignore storage restrictions in private/sandboxed frames
  }
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    setLangState(readStoredLang());
  }, []);

  const dir = useMemo<"ltr" | "rtl">(() => {
    const found = LANGS.find((l) => l.code === lang);
    return found?.dir ?? "ltr";
  }, [lang]);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = (next: LangCode) => {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Ignore storage restrictions
    }
  };

  const value = useMemo<I18nContextValue>(() => {
    const dict = TRANSLATIONS[lang] ?? EN;
    return {
      lang,
      dir,
      setLang,
      t: (key: string, fallback?: string) => dict[key] ?? EN[key] ?? fallback ?? key,
    };
  }, [lang, dir]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
